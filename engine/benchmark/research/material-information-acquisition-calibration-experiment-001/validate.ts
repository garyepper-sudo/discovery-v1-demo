import assert from "node:assert/strict";
import { runAblations } from "./ablation";
import { runCalibrationExperiment } from "./evaluator";
import { calibrationScenarios, sequentialScenarios, wordingPerturbations } from "./fixtures";
import { calibrationFixtures } from "./calibrationFixtures";
import { holdoutFixtures, negativeControlFixtures } from "./holdoutFixtures";
import { runSequentialCalibration } from "./sequential";
import { select } from "./selectors";

const first = { calibration: runCalibrationExperiment(), ablations: runAblations(), sequential: runSequentialCalibration() };
const second = { calibration: runCalibrationExperiment(), ablations: runAblations(), sequential: runSequentialCalibration() };
assert.deepEqual(first, second, "calibration must be deterministic");
assert.ok(first.calibration.scenarioCount >= 60, "at least sixty scenarios are required");
assert.ok(first.calibration.splitCounts.holdout >= 20, "at least twenty holdout scenarios are required");
assert.equal(new Set(calibrationFixtures.map(({ id }) => id)).size, calibrationFixtures.length);
assert.equal(new Set(holdoutFixtures.map(({ id }) => id)).size, holdoutFixtures.length);
assert.equal(calibrationFixtures.some(({ id }) => holdoutFixtures.some((holdoutScenario) => holdoutScenario.id === id)), false, "holdout must be separate from calibration and validation");
assert.equal(negativeControlFixtures.length, 4);
assert.ok(sequentialScenarios.length >= 10, "at least ten sequential scenarios are required");
const holdout = first.calibration.holdout.find((metrics) => metrics.selectorId === "H-calibrated-stop")!;
const phase2c = first.calibration.holdout.find((metrics) => metrics.selectorId === "A-phase2c")!;
assert.equal(holdout.governanceViolations, 0);
assert.equal(holdout.authorizationViolations, 0);
assert.ok(holdout.correctActionSelection - phase2c.correctActionSelection >= 0.1, "treatment must materially exceed Phase 2C baseline on holdout");
assert.ok(holdout.stoppingPrecision >= 0.9 && holdout.stoppingRecall >= 0.9, "stopping must be precise on holdout");
assert.equal(holdout.inputOrderStability, 1);
assert.equal(holdout.wordingStability, 1);
assert.equal(holdout.organizationIsolation, 1);
assert.equal(holdout.deterministicReplay, 1);
assert.equal(first.sequential.correctSequences, sequentialScenarios.length);
assert.equal(first.sequential.repeatedActionRate, 0);
assert.equal(first.sequential.stoppingRate, 1);
for (const scenario of calibrationScenarios.filter((candidate) => candidate.split === "negative-control")) assert.equal(select(scenario, "H-calibrated-stop").kind, "abstain");
for (const variant of wordingPerturbations) assert.ok(variant.wordingVariantOf);
console.log(`PASS material information acquisition calibration (${first.calibration.scenarioCount} scenarios, ${first.sequential.scenarioCount} sequences)`);
